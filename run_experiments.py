"""Portable stage launcher. Scientific routines remain in their original files."""
from __future__ import annotations

import argparse
import importlib.metadata
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent
CORE = ROOT / "Control_Theoretic_DP_Numerics"
CODE, RESULTS = CORE / "code", CORE / "results"
DATA = CORE / "data/fashion_mnist"
STUDIES = ROOT / "experiments"


def check_environment(require_tex: bool) -> None:
    if sys.version_info < (3, 11):
        raise SystemExit("Python 3.11 or newer is required; Python 3.12 is the reference environment.")
    try:
        version = importlib.metadata.version("numpy")
    except importlib.metadata.PackageNotFoundError:
        raise SystemExit("NumPy is missing. Run: python -m pip install -r requirements.txt")
    if version != "2.3.5":
        raise SystemExit(f"Expected NumPy 2.3.5, found {version}. Install requirements.txt in a fresh virtual environment.")
    if require_tex:
        if shutil.which("pdflatex") is None:
            raise SystemExit("Figure generation requires pdflatex. Install a TeX distribution, "
                             "or use 'all --no-figures' for numerical experiments only.")
        locator = shutil.which("kpsewhich")
        if locator:
            required = ["standalone.cls", "pgfplots.sty", "lmodern.sty",
                        "tikzlibrarypgfplots.groupplots.code.tex", "tikzlibrarypgfplots.fillbetween.code.tex"]
            missing = [name for name in required if subprocess.run(
                [locator, name], capture_output=True, text=True).returncode != 0]
            if missing:
                raise SystemExit("Missing TeX dependencies: " + ", ".join(missing))
    print(f"Environment ready: Python {sys.version.split()[0]}, NumPy {version}.", flush=True)


def check_prerequisites(stage: str) -> None:
    head = STUDIES / "nonlinear_allocation_2026_10_08"
    prediction = STUDIES / "network_performance_2026_10_09"
    solvers = STUDIES / "solver_comparison_2026_10_08"
    needed = {
        "lr": [(RESULTS / "comprehensive/config.json", "core"),
               (RESULTS / "comprehensive/raw_results.csv", "core")],
        "prediction": [(RESULTS / "comprehensive/config.json", "core"),
                       (RESULTS / "comprehensive/raw_results.csv", "core"),
                       (STUDIES / "lr_baseline_2026_10_08/results/verification.json", "lr")],
        "figures": [(head / "combined_summary.json", "head"),
                    (head / "final_audit.json", "head"),
                    (head / "confirmation/independent_mechanism_diagnostics.json", "head"),
                    (prediction / "results/verification.json", "prediction"),
                    (prediction / "results/summary.json", "prediction"),
                    (solvers / "results/verification.json", "solvers"),
                    (solvers / "armijo_results/verification.json", "solvers"),
                    (solvers / "penalty_results/verification.json", "solvers")],
    }
    if stage == "figures":
        for task in ["tabular", "fashion_constant", "fashion_restart"]:
            needed[stage] += [(RESULTS / "representative" / task / "schedules.csv", "core"),
                              (CORE / "paper_artifacts" / f"numerical_penalty_{task}.dat", "core")]
    missing = [(path, producer) for path, producer in needed.get(stage, []) if not path.is_file()]
    if missing:
        details = "\n".join(f"  {p.relative_to(ROOT)} (generated by '{producer}')" for p, producer in missing)
        stages = ", ".join(sorted({producer for _, producer in missing}))
        raise SystemExit(f"Stage '{stage}' is missing prerequisite outputs:\n{details}\nRun the required stages first: {stages}.")


def commands(stage: str, workers: int) -> list[list[str]]:
    py = sys.executable
    def script(path, *args):
        return [py, str(path), *map(str, args)]
    if stage == "core":
        result = [script(CODE / "dp_sgd_schedule_compare.py",
            "--out", RESULTS / "representative/tabular", "--seed", 17,
            "--K", 180, "--M-opt", 256, "--M-val", 512, "--M-eval", 512,
            "--rho", .5, "--q-min", 1e-5, "--clip", 4., "--delta", 1e-5,
            "--alphas", .005, "--pgd-alphas", "3e-5,1e-4,3e-4,1e-3")]
        for scenario, output, alpha in [("standard", "fashion_constant", .0005),
                                         ("lr_restart", "fashion_restart", .005)]:
            result.append(script(CODE / "fashion_mnist_mlp_schedule_compare.py",
                "--out", RESULTS / "representative" / output,
                "--data-dir", DATA, "--seed", 123, "--K", 100,
                "--M-opt", 8, "--M-val", 48, "--M-eval", 256,
                "--n-train", 8000, "--n-test", 3000, "--horizon", 45,
                "--batch-size", 192, "--hidden", 32, "--scenario", scenario,
                "--rho", .5, "--q-min", 1e-5, "--clip", 1.75,
                "--delta", 1e-5, "--alphas", alpha,
                "--pgd-alphas", "3e-6,1e-5,3e-5,1e-4"))
        for program, output in [("comprehensive_schedule_benchmark.py", "comprehensive"),
                                 ("published_schedule_baseline.py", "published_schedule"),
                                 ("proxy_transfer_study.py", "proxy_transfer")]:
            result.append(script(CODE / program, "--out", RESULTS / output,
                                 "--data-dir", DATA, "--workers", workers, "--resume"))
        result += [script(CODE / "controlled_runtime_benchmark.py",
                          "--out", RESULTS / "controlled_runtime", "--data-dir", DATA,
                          "--repeats", 3, "--resume"),
                   script(CODE / "numerical_validation_diagnostics.py",
                          "--out", RESULTS / "validation_diagnostics.json", "--data-dir", DATA),
                   script(CODE / "linear_quadratic_validation.py",
                          "--out", RESULTS / "linear_quadratic", "--horizon", 80,
                          "--rho", 1., "--q-min", .001, "--alpha", .0003,
                          "--iterations", 200000),
                   script(CODE / "export_concise_numerical_latex.py",
                          "--raw", RESULTS / "comprehensive/raw_results.csv",
                          "--published", RESULTS / "published_schedule/published_schedule_raw.csv",
                          "--runtime", RESULTS / "controlled_runtime/runtime_runs.csv",
                          "--lq", RESULTS / "linear_quadratic/result.json",
                          "--out-dir", CORE / "paper_artifacts"),
                   script(CODE / "verify_results.py", "--root", CORE,
                          "--results", RESULTS, "--out", RESULTS / "verification_report.json")]
        return result
    if stage == "lr":
        folder = STUDIES / "lr_baseline_2026_10_08"
        return [script(folder / "run_comparison.py", "--resume"),
                script(folder / "verify_comparison.py")]
    if stage == "head":
        return [script(ROOT / "run_head_final.py", "--workers", workers)]
    if stage == "prediction":
        folder = STUDIES / "network_performance_2026_10_09"
        return [script(folder / "test_study.py"), script(folder / "test_statistics.py"),
                script(folder / "run_study.py", "--workers", workers),
                script(folder / "verify_study.py", "--workers", workers),
                script(folder / "summarize.py")]
    if stage == "solvers":
        folder = STUDIES / "solver_comparison_2026_10_08"
        jobs = [("test_benchmark.py", []), ("benchmark.py", ["all"]),
                ("verify.py", ["--replay"]), ("test_armijo.py", []),
                ("armijo.py", []), ("verify_armijo.py", []),
                ("test_penalty_comparison.py", []), ("penalty_comparison.py", ["all"]),
                ("verify_penalty_comparison.py", []), ("analyze.py", []),
                ("analyze_armijo.py", [])]
        return [script(folder / program, *args) for program, args in jobs]
    raise ValueError(stage)


def build_figures(dry_run: bool) -> None:
    py = sys.executable
    jobs = [[py, str(STUDIES / name / "paper_update/build_figure.py")]
            for name in ["nonlinear_allocation_2026_10_08",
                         "network_performance_2026_10_09", "solver_comparison_2026_10_08"]]
    output = ROOT / "output/figures"
    if not dry_run:
        output.mkdir(parents=True, exist_ok=True)
    for job in jobs:
        execute(job, dry_run)
    sources = [CORE / "figures/figure_allocation_regimes.tex",
               CORE / "figures/figure_penalty_charge.tex"]
    sources += [STUDIES / name / "paper_update" / (figure + ".tex")
                for name, figure in [("nonlinear_allocation_2026_10_08", "figure_nonlinear_mechanism"),
                                     ("network_performance_2026_10_09", "figure_network_performance"),
                                     ("solver_comparison_2026_10_08", "figure_solver_efficiency")]]
    for source in sources:
        # Keep TeX-visible paths relative and ASCII. Absolute paths containing
        # non-ASCII characters fail inside PGFPlots table filename expansion.
        tex = (r"\def\resultroot{" + RESULTS.relative_to(ROOT).as_posix() + "}"
               + r"\def\artifactroot{" + (CORE / "paper_artifacts").relative_to(ROOT).as_posix() + "}"
               + r"\input{" + source.relative_to(ROOT).as_posix() + "}")
        job = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
               "-output-directory", str(output.relative_to(ROOT)), "-jobname", source.stem, tex]
        # PGFPlots named legends need a second pass.
        execute(job, dry_run)
        execute(job, dry_run)


def execute(command: list[str], dry_run: bool) -> None:
    print("+ " + shlex.join(command), flush=True)
    if not dry_run:
        subprocess.run(command, cwd=ROOT, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=["core", "lr", "head", "prediction", "solvers", "figures", "all"])
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--dry-run", action="store_true", help="Print commands without running or downloading")
    parser.add_argument("--no-figures", action="store_true", help="For 'all': run numerical stages without requiring LaTeX")
    parser.add_argument("--check-only", action="store_true", help="Check environment, local data and prerequisites without running experiments")
    args = parser.parse_args()
    if args.workers < 1:
        parser.error("--workers must be positive")
    if args.no_figures and args.stage != "all":
        parser.error("--no-figures is only used with the 'all' stage")
    for name in ["OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS",
                 "VECLIB_MAXIMUM_THREADS", "BLIS_NUM_THREADS"]:
        os.environ[name] = "1"
    os.environ["PYTHONDONTWRITEBYTECODE"] = "1"
    os.environ["PYTHONUTF8"] = "1"
    stages = ["core", "lr", "head", "prediction", "solvers", "figures"] if args.stage == "all" else [args.stage]
    if args.no_figures:
        stages.remove("figures")
    if not args.dry_run:
        check_environment(require_tex="figures" in stages)
        if args.stage != "figures":
            execute([sys.executable, str(ROOT / "prepare_data.py"), "--check-only"], False)
    if args.check_only:
        if not args.dry_run:
            check_prerequisites(stages[0])
            print("Preflight checks passed; no experiment was started.", flush=True)
        return
    for stage in stages:
        if not args.dry_run:
            check_prerequisites(stage)
        if stage == "figures":
            build_figures(args.dry_run)
        else:
            for command in commands(stage, args.workers):
                execute(command, args.dry_run)


if __name__ == "__main__":
    main()
